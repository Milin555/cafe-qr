# -*- coding: utf-8 -*-
"""Cafe QR — static menu renderer.

One engine, many cafes. Reads cafes/<id>/cafe.json + menu.json + assets/,
emits a self-contained page (assets inlined as data URIs, so it works from
GitHub Pages, a file:// URL, or an Artifact with no external requests).

    python3 build/render.py sorriso
"""
import base64, hashlib, json, mimetypes, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "build"))
from icons import ICONS, UI

# ---------------------------------------------------------------- helpers
def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))

def data_uri(path):
    mime = mimetypes.guess_type(path)[0] or "application/octet-stream"
    with open(path, "rb") as f:
        return "data:%s;base64,%s" % (mime, base64.b64encode(f.read()).decode())

def icon(key, cls="ico", sw="1.4"):
    body = ICONS.get(key) or UI.get(key) or UI["sparkle"]
    return ('<svg class="%s" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            'stroke-width="%s" stroke-linecap="round" stroke-linejoin="round" '
            'aria-hidden="true">%s</svg>' % (cls, sw, body))

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

SW = r"""/* Cafe QR offline shell — generated by build/render.py, do not edit. */
var C = "__CACHE__", SHELL = __SHELL__;

self.addEventListener("install", function(e){
  // warm the shell so even a first-visit-then-offline still shows the menu
  e.waitUntil(caches.open(C).then(function(c){
    return c.addAll(SHELL).catch(function(){});
  }).then(function(){ return self.skipWaiting(); }));
});

self.addEventListener("activate", function(e){
  e.waitUntil(caches.keys().then(function(ks){
    return Promise.all(ks.map(function(k){
      // only ever touch this cafe's own caches
      if(k !== C && k.indexOf("__SCOPE__-") === 0) return caches.delete(k);
    }));
  }).then(function(){ return self.clients.claim(); }));
});

// A clone must be taken before the response is handed to the page, or the body
// is already disturbed by the time the cache write runs, and nothing is stored.
function keep(e, req, res){
  if(res && res.ok){
    var copy = res.clone();
    e.waitUntil(caches.open(C).then(function(c){ return c.put(req, copy); }));
  }
  return res;
}

self.addEventListener("fetch", function(e){
  var r = e.request;
  if(r.method !== "GET") return;
  var u = new URL(r.url);
  if(u.origin !== location.origin) return;

  // assets are versioned by the build and marked immutable: cache first
  if(u.pathname.indexOf("/assets/") > -1){
    e.respondWith(caches.match(r).then(function(hit){
      return hit || fetch(r).then(function(res){ return keep(e, r, res); });
    }));
    return;
  }

  // the menu itself is network-first, so a published price change is never stale
  if(r.mode === "navigate" || u.pathname.slice(-1) === "/" || u.pathname.slice(-5) === ".html"){
    e.respondWith(
      fetch(r).then(function(res){ return keep(e, r, res); })
        .catch(function(){
          return caches.match(r).then(function(hit){
            return hit || caches.match("./") || Response.error();
          });
        })
    );
  }
});
"""

# ---------------------------------------------------------------- build
def build(cafe_id):
    cdir = os.path.join(ROOT, "cafes", cafe_id)
    cafe = json.load(open(os.path.join(cdir, "cafe.json"), encoding="utf-8"))
    menu = json.load(open(os.path.join(cdir, "menu.json"), encoding="utf-8"))
    adir = os.path.join(cdir, "assets")
    names = {k: v for k, v in cafe["assets"].items()
             if isinstance(v, str) and os.path.exists(os.path.join(adir, v))}
    A_data = {k: data_uri(os.path.join(adir, v)) for k, v in names.items()}
    A_rel = {k: "assets/" + v for k, v in names.items()}
    for k in ("logo", "hero", "pattern", "artCup", "artShake"):
        A_data.setdefault(k, "")
        A_rel.setdefault(k, "")
    gal = [g for g in cafe["assets"].get("gallery", []) if os.path.exists(os.path.join(adir, g))]
    gal_data = [data_uri(os.path.join(adir, g)) for g in gal]
    gal_rel = ["assets/" + g for g in gal]
    A = A_data

    t, c, addr, hrs = cafe["theme"], cafe["contact"], cafe["address"], cafe["hours"]
    cur = menu.get("currency", "₹")

    def price_html(i):
        if i.get("price") in (None, "", 0):
            return ('<span class="dots"></span>'
                    '<span class="price price-ask">at the counter</span>')
        return ('<span class="dots"></span>'
                '<span class="price">%s%s</span>' % (cur, i["price"]))

    full_addr = ", ".join([addr["line1"], addr["line2"], addr["line3"],
                           addr["city"], addr["state"], addr["pin"]])

    idir = os.path.join(adir, "items")
    have_photo = set()
    if os.path.isdir(idir):
        have_photo = {f[:-4] for f in os.listdir(idir)
                      if f.endswith(".jpg") and not f.endswith("-lg.jpg")}

    all_items = [i for sec in menu["sections"] for i in sec["items"]]
    all_veg = all(i.get("veg") for i in all_items)

    # ---- picks (items flagged in the data, never invented here)
    picks = [(s, i) for s in menu["sections"] for i in s["items"] if i.get("tag")]

    # ---- nav
    nav = "".join(
        '<a class="pill" href="#s-%s" data-nav="%s">%s</a>' % (s["id"], s["id"], esc(s["name"]))
        for s in menu["sections"])

    # ---- picks rail
    pick_cards = "".join(
        '<a class="pick" href="#s-%s"><span class="pick-ico">%s</span>'
        '<span class="pick-tag">%s</span><span class="pick-name">%s</span>'
        '<span class="pick-price">%s</span></a>'
        % (s["id"], icon(i["icon"], "ico", "1.25"), esc(s["name"]), esc(i["name"]),
           ("%s%s" % (cur, i["price"])) if i.get("price") else "at the counter")
        for s, i in picks)

    # ---- sections
    def item_row(i, sec_name=""):
        veg = "" if all_veg else (
            '<span class="veg" title="Vegetarian" aria-label="Vegetarian"><i></i></span>'
            if i.get("veg") else "")
        tag = ('<span class="tag">%s</span>' % esc(i["tag"])) if i.get("tag") else ""
        note = ('<p class="note">%s</p>' % esc(i["note"])) if i.get("note") else ""
        ph = i.get("photo") or (slug(i["name"]) if slug(i["name"]) in have_photo else None)
        if ph:
            tile = ('<span class="tile photo"><img src="%sitems/%s.jpg" alt="%s" '
                    'loading="lazy" decoding="async" width="46" height="46"></span>'
                    % ("__IMGBASE__", ph, esc(i["name"])))
        else:
            tile = '<span class="tile">%s</span>' % icon(i["icon"])
        big = ('<img class="shotbig" src="%sitems/%s-lg.jpg" alt="%s" loading="lazy" '
               'decoding="async">' % ("__IMGBASE__", ph, esc(i["name"]))) if ph else ""
        desc = i.get("desc", "")
        search = esc((i["name"] + " " + i.get("note", "") + " " + desc
                      + " " + sec_name).lower())
        if desc or ph:
            body = ('<span class="body">'
                    '<button class="line" type="button" aria-expanded="false">'
                    '<span class="name">%s%s<i class="chev" aria-hidden="true"></i></span>%s'
                    '%s</button>%s'
                    '<div class="detail" hidden>%s%s</div></span>'
                    % (esc(i["name"]), veg, tag, price_html(i), note, big,
                       ('<p class="desc">%s</p>' % esc(desc)) if desc else ""))
            cls = "item has-desc"
        else:
            body = ('<span class="body"><span class="line">'
                    '<span class="name">%s%s</span>%s'
                    '%s</span>%s</span>'
                    % (esc(i["name"]), veg, tag, price_html(i), note))
            cls = "item"
        return '<li class="%s" data-q="%s">%s%s</li>' % (cls, search, tile, body)

    secs = "".join(
        '<section class="sec reveal" id="s-%s" data-sec="%s">'
        '<header class="sec-h"><p class="kicker">%s</p><h2>%s</h2>'
        '<span class="rule"></span></header><ul class="items">%s</ul></section>'
        % (s["id"], s["id"], esc(s.get("kicker", "")), esc(s["name"]),
           "".join(item_row(i, s["name"]) for i in s["items"]))
        for s in menu["sections"])

    # ---- add-ons
    ad = menu["addons"]
    addon_groups = "".join(
        '<div class="ag"><span class="tile sm">%s</span><div>'
        '<p class="ag-h">%s<span class="ag-p">%s</span></p>'
        '<p class="ag-o">%s</p></div></div>'
        % (icon(g["icon"], "ico", "1.3"), esc(g["label"]),
           ("%s%s" % (cur, g["price"])) if g.get("price") else "",
           esc(" · ".join(g["options"])))
        for g in ad["groups"])

    action = lambda href, ic, label, extra="": (
        '<a class="act" href="%s"%s><span>%s</span>%s</a>'
        % (href, extra, icon(ic, "ico", "1.5"), esc(label)))
    blank = ' target="_blank" rel="noopener"'
    actions = action(c["directions"], "directions", "Directions", blank)
    if c.get("whatsapp"): actions += action(c["whatsapp"], "whatsapp", "WhatsApp", blank)
    if c.get("phone"):    actions += action("tel:" + c["phone"], "phone", "Call")
    if c.get("instagram"):actions += action(c["instagram"], "instagram", "Instagram", blank)

    open_h, close_h = hrs["open"], hrs["close"]
    TPL = open(os.path.join(ROOT, "build", "page.html"), encoding="utf-8").read()
    rep = {
        "@@CAFEID@@": cafe_id,
        "@@NAME@@": esc(cafe["name"]),
        "@@TAGLINE@@": esc(cafe["tagline"]),
        "@@EYEBROW@@": esc(cafe.get("eyebrow", " · ".join(cafe["meta"]["cuisines"][:2]))),
        "@@BLURB@@": esc(cafe["blurb"]),
        "@@LOGO@@": A["logo"], "@@HERO@@": A["hero"],
        "@@PATTERN@@": A["pattern"], "@@ARTCUP@@": A["artCup"],
        "@@ARTSHAKE@@": A["artShake"],
        "@@RATING@@": str(cafe["meta"]["rating"]),
        "@@RATINGCOUNT@@": str(cafe["meta"]["ratingCount"]),
        "@@RATINGSRC@@": esc(cafe["meta"]["ratingSource"]),
        "@@PRICEBAND@@": esc(cafe["meta"]["priceBand"]),
        "@@CUISINES@@": esc(" · ".join(cafe["meta"]["cuisines"])),
        "@@HOURS@@": esc(hrs["label"]), "@@DAYS@@": esc(hrs["days"]),
        "@@OPENH@@": open_h, "@@CLOSEH@@": close_h,
        "@@ADDR1@@": esc(addr["line1"]),
        "@@ADDR2@@": esc(addr["line2"] + ", " + addr["line3"]),
        "@@ADDR3@@": esc("%s, %s %s" % (addr["city"], addr["state"], addr["pin"])),
        "@@FULLADDR@@": esc(full_addr),
        "@@PHONE@@": c["phone"], "@@PHONEDISP@@": esc(c["phoneDisplay"]),
        "@@WHATSAPP@@": c.get("whatsapp",""), "@@INSTA@@": c.get("instagram",""),
        "@@INSTAH@@": esc(c.get("instagramHandle","")),
        "@@REVIEW@@": c.get("googleReview",""), "@@DIRECTIONS@@": c["directions"],
        "@@FOOTERLINKS@@": "".join(filter(None, [
            '<a class="f-btn" href="%s"%s>%sDirections</a>' % (c["directions"], blank, icon("directions","ico","1.4")),
            ('<a class="f-btn" href="tel:%s">%s%s</a>' % (c["phone"], icon("phone","ico","1.4"), esc(c["phoneDisplay"]))) if c.get("phone") else "",
            ('<a class="f-btn" href="%s"%s>%sBook a table</a>' % (c["whatsapp"], blank, icon("whatsapp","ico","1.4"))) if c.get("whatsapp") else "",
            ('<a class="f-btn" href="%s"%s>%s%s</a>' % (c["instagram"], blank, icon("instagram","ico","1.4"), esc(c.get("instagramHandle","Instagram")))) if c.get("instagram") else "",
            ('<a class="f-btn gold" href="%s"%s>%sLeave a review</a>' % (c["googleReview"], blank, icon("star","ico","1.4"))) if c.get("googleReview") else "",
        ])),
        "@@NAV@@": nav, "@@PICKS@@": pick_cards, "@@SECTIONS@@": secs,
        "@@ADDONTITLE@@": esc(ad["title"]), "@@ADDONS@@": addon_groups,
        "@@ACTIONS@@": actions,
        "@@GALLERYTITLE@@": esc(cafe.get("galleryTitle", "The room")),
        "@@PICKSTITLE@@": esc(cafe.get("picksTitle", "Guests keep ordering")),
        "@@SEARCHHINT@@": esc(cafe.get("searchHint", "Try a name, or an ingredient")),
        "@@PRICELABEL@@": esc(cafe.get("priceLabel", "per person")),
        "@@RATINGCELL@@": ("" if not cafe["meta"].get("showRating", True) else
            '<div><b>%s%s</b><span>%s reviews</span></div>'
            % (icon("star", "ico", "1.3"), cafe["meta"]["rating"], cafe["meta"]["ratingCount"])),
        "@@STRIP@@": ('<div class="strip" aria-hidden="true"></div>'
                      if cafe["assets"].get("pattern") else ""),
        "@@FSTRIP@@": ('<div class="f-strip" aria-hidden="true"></div>'
                       if cafe["assets"].get("pattern") else ""),
        "@@GALLERY@@": ("" if not gal else
            '<div class="gal-wrap reveal">'
            '<div class="rail-h" style="padding-left:0;padding-right:0"><p>%s</p><i></i></div>'
            '<div class="gal">@@SHOTS@@</div></div>'
            % esc(cafe.get("galleryTitle", "The room"))),
        "@@ITEMCOUNT@@": str(sum(len(s["items"]) for s in menu["sections"])),
        "@@VEGNOTE@@": ('<p class="vegnote"><span class="veg"><i></i></span>'
                        'Pure vegetarian kitchen</p>') if all_veg else "",
        "@@SECCOUNT@@": str(len(menu["sections"])),
        "@@CAPTURED@@": esc(__import__("datetime").datetime.strptime(
            cafe["source"]["capturedOn"], "%Y-%m-%d").strftime("%-d %B %Y")),
        "@@ISTAR@@": icon("star", "ico", "1.3"),
        "@@ICLOCK@@": icon("clock", "ico", "1.4"),
        "@@IPIN@@": icon("pin", "ico", "1.4"),
        "@@ISEARCH@@": icon("search", "ico", "1.6"),
        "@@ICLOSE@@": icon("close", "ico", "1.8"),
        "@@IARROW@@": icon("arrow", "ico", "1.7"),
        "@@ISUN@@": icon("sun", "ico", "1.5"),
        "@@IMOON@@": icon("moon", "ico", "1.5"),
        "@@ILEAF@@": icon("leaf", "ico", "1.3"),
        "@@IREVIEW@@": icon("star", "ico", "1.4"),
        "@@IINSTA@@": icon("instagram", "ico", "1.4"),
        "@@IWA@@": icon("whatsapp", "ico", "1.4"),
        "@@IPHONE@@": icon("phone", "ico", "1.4"),
        "@@IDIR@@": icon("directions", "ico", "1.4"),
    }
    for k, v in t.items():
        rep["@@T_" + k.upper() + "@@"] = v
    for k, v in cafe.get("themeDark", {}).items():
        rep["@@D_" + k.upper() + "@@"] = v
    def render(assets, gal, imgbase):
        out = TPL.replace("__IMGBASE__", imgbase)
        local = dict(rep)
        local["@@HEROIMG@@"] = ('<img class="hero-bg" src="%s" alt="" aria-hidden="true" '
                                'fetchpriority="high">' % assets["hero"]) if assets.get("hero") else ""
        local.update({"@@LOGO@@": assets["logo"], "@@HERO@@": assets["hero"],
                      "@@PATTERN@@": assets["pattern"], "@@ARTCUP@@": assets["artCup"],
                      "@@ARTSHAKE@@": assets["artShake"]})
        caps = cafe.get("galleryCaptions", [])
        local["@@SHOTS@@"] = "".join(
            '<figure class="shot"><img src="%s" alt="%s" loading="lazy" decoding="async">'
            '<figcaption>%s</figcaption></figure>'
            % (g, esc((caps[n] if n < len(caps) else cafe["name"]) + " at " + cafe["name"]),
               esc(caps[n] if n < len(caps) else ""))
            for n, g in enumerate(gal))
        for k, v in local.items():
            out = out.replace(k, v.replace("__IMGBASE__", imgbase) if isinstance(v, str) else v)
        return out

    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
    frag = os.path.join(ROOT, "dist", "%s.artifact.html" % cafe_id)
    with open(frag, "w", encoding="utf-8") as f:
        frag_html = render(A_data, gal_data, "assets/")
        for name in sorted(os.listdir(idir)) if os.path.isdir(idir) else []:
            frag_html = frag_html.replace('src="assets/items/%s"' % name,
                                          'src="%s"' % data_uri(os.path.join(idir, name)))
        f.write(frag_html)

    site = os.path.join(ROOT, "docs", cafe_id)
    os.makedirs(site, exist_ok=True)
    import shutil
    sassets = os.path.join(site, "assets")
    if os.path.isdir(sassets):
        shutil.rmtree(sassets)
    shutil.copytree(adir, sassets)
    tpl = render(A_rel, gal_rel, "assets/")

    # A menu reached by QR is read at a table, on cafe wifi, sometimes while the
    # host is redeploying. The service worker keeps the last good copy: the page
    # is network-first so a price edit is live the moment it publishes, and
    # assets are cache-first because vercel.json marks them immutable. Scope is
    # /<cafe-id>/, so one cafe's cache can never serve another's menu.
    ver = hashlib.sha1(tpl.encode("utf-8")).hexdigest()[:10]
    shell = ["./"] + sorted(set(list(A_rel.values()) + gal_rel))
    sw = (SW.replace("__CACHE__", "%s-%s" % (cafe_id, ver))
            .replace("__SCOPE__", cafe_id)
            .replace("__SHELL__", json.dumps(shell)))
    with open(os.path.join(site, "sw.js"), "w", encoding="utf-8") as f:
        f.write(sw)

    doc = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
           '<meta name="viewport" content="width=device-width,initial-scale=1">'
           '<meta name="theme-color" media="(prefers-color-scheme:light)" content="%s">'
           '<meta name="theme-color" media="(prefers-color-scheme:dark)" content="%s">'
           '<meta name="description" content="%s">'
           '<meta property="og:type" content="website">'
           '<meta property="og:site_name" content="%s">'
           '<meta property="og:title" content="%s — Menu">'
           '<meta property="og:description" content="%s">'
           '<meta property="og:image" content="%s">'
           '<meta name="twitter:card" content="summary_large_image">'
           '<link rel="icon" href="%s">'
           '<style>html,body{margin:0}img{max-width:100%%}</style>'
           '</head><body>%s'
           '<script>if("serviceWorker"in navigator)addEventListener("load",function(){'
           'navigator.serviceWorker.register("sw.js").catch(function(){})});</script>'
           '</body></html>'
           % (t["bg"], cafe.get("themeDark", {}).get("bg", t["bg"]), esc(cafe["blurb"]), esc(cafe["name"]), esc(cafe["name"]),
              esc(cafe["blurb"]), A_rel.get("hero") or A_rel["logo"],
              A_rel["logo"], tpl))
    with open(os.path.join(site, "index.html"), "w", encoding="utf-8") as f:
        f.write(doc)

    kb = lambda p: os.path.getsize(p) / 1024.0
    print("built %s  ->  dist/%s.artifact.html (%.0f KB)  docs/%s/index.html (%.0f KB)"
          % (cafe_id, cafe_id, kb(frag), cafe_id, kb(os.path.join(site, "index.html"))))
    print("       %s sections, %s items, %s picks"
          % (len(menu["sections"]), rep["@@ITEMCOUNT@@"], len(picks)))

if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "sorriso")
